def build_year() -> int:
    """سال شمسی ساخت/نسخهٔ جاری (برای نمایش «سال ساخت»)."""
    jy, _, _ = to_jalali(_dt.date.today())
    return jy


def build_year_gregorian() -> int:
    return _dt.date.today().year


def year_label(today: _dt.date | None = None) -> str:
    """«۱۴۰۵ / ۲۰۲۶» — سال ساخت با اعداد فارسی."""
    day = today or _dt.date.today()
    jy, _, _ = to_jalali(day)
    return "%s / %s" % (fa_digits(str(jy)), fa_digits(str(day.year)))


def copyright_line(today: _dt.date | None = None) -> str:
    return "© %s — %s — %s" % (year_label(today), COPYRIGHT_HOLDER,
                               "تمام حقوق محفوظ است")


def version_line() -> str:
    return "نسخه %s  ·  ساخت %s" % (fa_digits(APP_VERSION), year_label())


